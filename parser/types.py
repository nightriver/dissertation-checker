"""
types.py
Спільні типи, константи та предикати для всіх модулів пакету parser.
"""

import re
from enum import Enum
from typing import TypedDict


class LineItem(TypedDict):
    """Один рядок документа з номером сторінки."""
    line: str
    page: int | None


class Severity(Enum):
    """
    Спільна шкала для всіх аналітичних перевірок (анахронізми, дублікати,
    гомогліфи) — щоб UI малював їх однаково.

    PROOF   — технічно неможливо, пояснити оформленням не можна.
    SUSPECT — аномалія: потрібен погляд людини, вироку немає.
    """
    PROOF   = "proof"
    SUSPECT = "suspect"


# Максимально допустимий порядковий номер джерела.
#
# Використовується З ОБОХ БОКІВ порівняння:
#   • bibliography._is_valid_entry — щоб «2005.» у тексті запису не стало
#     новим джерелом №2005;
#   • citations._parse_token       — щоб «[2020]» чи індекс масиву «a[0]»
#     не стали посиланнями на джерела.
#
# Числа понад 999 — це роки або номери документів, а не порядкові номери.
# Реальна дисертація має щонайбільше ~500 джерел.
MAX_SOURCE_NUM = 999


# ---------------------------------------------------------------------------
# Розпізнавання рядків ЗМІСТу
# ---------------------------------------------------------------------------

# Рядок змісту з крапковими лідерами: "РОЗДІЛ 1. ОГЛЯД ...... 12".
# Консервативний варіант — його можна застосовувати й до звичайних абзаців.
TOC_LEADER_RE = re.compile(r'\.{3,}\s*\d*\s*$')

# Ширший варіант: Word будує ЗМІСТ на табуляції або на вирівнюванні пробілами,
# без крапок — "РОЗДІЛ 1. ОГЛЯД	12", "ВИСНОВКИ   180".
# Застосовувати ТІЛЬКИ до рядків, які вже схожі на заголовок, інакше можна
# зачепити звичайний текст, що закінчується числом.
_TOC_ENTRY_RE = re.compile(r'(\.{3,}\s*\d*|	+\s*\d{1,4}|\s{2,}\d{1,4})\s*$')


def is_toc_entry(line: str) -> bool:
    """True якщо рядок виглядає як запис ЗМІСТу, а не справжній заголовок."""
    return bool(_TOC_ENTRY_RE.search(line.strip()))
