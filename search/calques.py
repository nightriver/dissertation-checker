def find_calques_with_rejections(
    block: SearchBlock,
) -> tuple[tuple[CalqueHit, ...], tuple[CalqueRejection, ...]]:
    """
    Усі збіги активних правил у блоці плюс відсіяні збіги з причиною (§8.3).
    Правило зі `status == "excluded"` не виконується взагалі.
    """
    text = block.normalized.text
    hits: list[CalqueHit] = []
    rejections: list[CalqueRejection] = []
    if not text:
        return (), ()

    for rule in CALQUES:
        if rule.status != "active" or rule.tier is None:
            continue
        for match in compile_pattern(rule.pattern).finditer(text):
            raw_start, raw_end = _raw_bounds(block, match.start(), match.end())
            matched_text = block.raw_text[raw_start:raw_end]
            window = _context_window(block, raw_start, raw_end)
            if rule.required_context and not _context_present(
                window, rule.required_context
            ):
                rejections.append(
                    CalqueRejection(
                        rule.rule_id,
                        REASON_REQUIRED_CONTEXT_MISSING,
                        raw_start,
                        raw_end,
                        matched_text,
                    )
                )
                continue
            if rule.forbidden_context and _context_present(
                window, rule.forbidden_context
            ):
                rejections.append(
                    CalqueRejection(
                        rule.rule_id,
                        REASON_FORBIDDEN_CONTEXT_PRESENT,
                        raw_start,
                        raw_end,
                        matched_text,
                    )
                )
                continue
            hits.append(
                CalqueHit(
                    rule_id=rule.rule_id,
                    tier=rule.tier,
                    raw_start=raw_start,
                    raw_end=raw_end,
                    matched_text=matched_text,
                    zone=resolve_zone(block.zone_spans, raw_start, raw_end),
                )
            )

    hits.sort(key=lambda hit: (hit.raw_start, hit.rule_id))
    rejections.sort(key=lambda rej: (rej.raw_start, rej.rule_id, rej.reason))
    return tuple(hits), tuple(rejections)


def find_calques(block: SearchBlock) -> tuple[CalqueHit, ...]:
    """
    Збіги активних правил у блоці, за зростанням `raw_start`, потім
    `rule_id` (§8.3). Зона кожного збігу береться з `zone_spans` блоку за
    інтервалом символів збігу, а не з мітки всього блоку.
    """
    hits, _ = find_calques_with_rejections(block)
    return hits


def collapse_components(hits: tuple[CalqueHit, ...]) -> tuple[CalqueHit, ...]:
    """
    Представники компонент перетинних збігів (§8.4). Перетинні збіги
    утворюють компоненту, і для чисельника щільності вона рахується один
    раз: найдовший span, потім менший `tier`, потім лексикографічно менший
    `rule_id`. Решта збігів не зникає — повний список лишається у
    викликача (`find_calques`), функція просто повертає представників.
    """
    if not hits:
        return ()
    ordered = sorted(hits, key=lambda hit: (hit.raw_start, hit.raw_end, hit.rule_id))
    representatives: list[CalqueHit] = []
    component: list[CalqueHit] = [ordered[0]]
    component_end = ordered[0].raw_end
    for hit in ordered[1:]:
        if hit.raw_start < component_end:
            component.append(hit)
            component_end = max(component_end, hit.raw_end)
        else:
            representatives.append(_component_representative(component))
            component = [hit]
            component_end = hit.raw_end
    representatives.append(_component_representative(component))
    representatives.sort(key=lambda hit: (hit.raw_start, hit.rule_id))
    return tuple(representatives)


def _component_representative(component: list[CalqueHit]) -> CalqueHit:
    return min(
        component,
        key=lambda hit: (
            -(hit.raw_end - hit.raw_start),
            hit.tier,
            hit.rule_id,
        ),
    )


def tier2_is_scorable(hits: tuple[CalqueHit, ...]) -> bool:
    """
    Чи дає рівень 2 бал у цьому блоці (§8.3): лише за наявності рівня 1 в
    авторському тексті того самого блоку. Показується рівень 2 завжди —
    відсів стосується тільки балу.
    """
    return any(
        hit.tier == 1 and hit.zone == TextZone.AUTHOR_TEXT for hit in hits
    )


