@dataclass(frozen=True)
class CalqueHit:
    """Один зарахований збіг правила у блоці. Координати — вихідний текст."""

    rule_id: str
    tier: int
    raw_start: int
    raw_end: int
    matched_text: str
    zone: TextZone


# Причини відсіву (§8, таблиця відмов). Нічого не глушиться мовчки
# (CLAUDE.md, правило №3): відсіяний збіг лишається з причиною.
REASON_RULE_EXCLUDED = "rule_excluded"
REASON_REQUIRED_CONTEXT_MISSING = "required_context_missing"
REASON_FORBIDDEN_CONTEXT_PRESENT = "forbidden_context_present"
REASON_EXCLUDED_ZONE = "excluded_zone"
REASON_TIER2_WITHOUT_TIER1 = "tier2_without_tier1"
REASON_TIER3_STATISTICAL_ONLY = "tier3_statistical_only"

REJECTION_REASONS: tuple[str, ...] = (
    REASON_RULE_EXCLUDED,
    REASON_REQUIRED_CONTEXT_MISSING,
    REASON_FORBIDDEN_CONTEXT_PRESENT,
    REASON_EXCLUDED_ZONE,
    REASON_TIER2_WITHOUT_TIER1,
    REASON_TIER3_STATISTICAL_ONLY,
)

# Зони, збіги в яких не потрапляють до щільності (§8.4). Порядок — з
# `ZONE_PRIORITY`, щоб діагностика була відтворюваною.
EXCLUDED_ZONES: tuple[TextZone, ...] = tuple(
    zone for zone in ZONE_PRIORITY if zone != TextZone.AUTHOR_TEXT
)


@dataclass(frozen=True)
class CalqueRejection:
    """Збіг, який не зараховано, і причина з `REJECTION_REASONS`."""

    rule_id: str
    reason: str
    raw_start: int
    raw_end: int
    matched_text: str


@lru_cache(maxsize=512)
def compile_pattern(pattern: str) -> re.Pattern[str]:
    """
    Скомпільований регулярний вираз за текстом самого шаблону (§8.1).

    Кеш свідомо ключується РЯДКОМ ШАБЛОНУ, а не `rule_id`: словник із
    ключами `rule_id` був би другою копією `CALQUES` і розходився б з ним
    щоразу, коли список підмінюють (тест, майбутній профіль правил). За
    ключем-шаблоном підміна словника нічого не ламає: невідомий шаблон
    просто компілюється вперше.
    """
    return re.compile(pattern, re.IGNORECASE | re.UNICODE)


def compiled_pattern(rule_id: str) -> re.Pattern[str]:
    """Скомпільована регулярка правила. Копій регулярок поза словником немає."""
    return compile_pattern(rule_by_id(rule_id).pattern)


def rule_by_id(rule_id: str) -> CalqueRule:
    """
    Правило за ідентифікатором. Пошук іде по чинному `CALQUES`, а не по
    заздалегідь побудованому індексу: єдине джерело істини — сам список.
    """
    for rule in CALQUES:
        if rule.rule_id == rule_id:
            return rule
    raise KeyError(rule_id)


def excluded_rule_ids() -> tuple[str, ...]:
    """
    Ідентифікатори правил, знеструмлених аудитом §8.2. Обчислюється щоразу
    з `CALQUES`: причина відсіву `rule_excluded` не має власної копії списку.
    """
    return tuple(rule.rule_id for rule in CALQUES if rule.status == "excluded")


