def resolve_zone(
    zone_spans: tuple[ZoneSpan, ...], raw_start: int, raw_end: int
) -> TextZone:
    """
    Зона півінтервалу вихідного тексту (§8.3): перемагає зона з найбільшим
    перекриттям, за рівного перекриття — перша з `ZONE_PRIORITY` (§4.1).
    Інтервал, не вкритий жодним `ZoneSpan`, лишається `UNCERTAIN`: мітка
    всього блоку тут не використовується навмисно.
    """
    if raw_end <= raw_start:
        raw_end = raw_start + 1
    overlaps: dict[TextZone, int] = {}
    for span in zone_spans:
        overlap = min(raw_end, span.raw_end) - max(raw_start, span.raw_start)
        if overlap > 0:
            overlaps[span.zone] = overlaps.get(span.zone, 0) + overlap
    if not overlaps:
        return TextZone.UNCERTAIN
    best = max(overlaps.values())
    for zone in ZONE_PRIORITY:
        if overlaps.get(zone, 0) == best:
            return zone
    return TextZone.UNCERTAIN  # недосяжно: ZONE_PRIORITY містить усі зони


def _context_window(
    block: SearchBlock, raw_start: int, raw_end: int
) -> tuple[str, ...]:
    """
    До `CONTEXT_WINDOW_TOKENS` словесних токенів ліворуч і стільки ж
    праворуч від збігу, у нижньому регістрі. Розділові знаки вікна не
    витрачають, токени самого збігу до вікна не входять (§8.3).
    """
    before: list[str] = []
    after: list[str] = []
    for token in block.tokens:
        if not token.is_word:
            continue
        if token.raw_end <= raw_start:
            before.append(token.normalized.casefold())
        elif token.raw_start >= raw_end:
            after.append(token.normalized.casefold())
    return tuple(before[-CONTEXT_WINDOW_TOKENS:] + after[:CONTEXT_WINDOW_TOKENS])


def _context_present(window: tuple[str, ...], needles: tuple[str, ...]) -> bool:
    """Чи є у вікні словесний токен, що починається з одного з коренів."""
    return any(word.startswith(needle) for word in window for needle in needles)


def _raw_bounds(block: SearchBlock, start: int, end: int) -> tuple[int, int]:
    """
    Півінтервал нормалізованого тексту → півінтервал вихідного `raw_text`.
    Блок без карти `origins` (штучно зібраний у тесті) деградує до
    нормалізованих координат, а не падає.
    """
    if len(block.normalized.origins) != len(block.normalized.text):
        return start, end
    parts = map_normalized_offsets(block.normalized, start, end)
    return parts[0][0], parts[-1][1]


